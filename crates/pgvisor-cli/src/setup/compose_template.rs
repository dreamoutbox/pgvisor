use std::fmt::Write as _;

use crate::cli::S3Mode;
use crate::setup::setup_options::SetupOptions;

/// Renders a standalone `docker-compose.yml` for a PgVisor HA cluster.
pub struct ComposeTemplate;

impl ComposeTemplate {
    /// Renders the complete `docker-compose.yml` matching `SetupOptions`.
    pub fn render(options: &SetupOptions) -> String {
        let mut out = String::with_capacity(4096);
        let bundled = options.s3_mode == S3Mode::Bundled;

        out.push_str("# Generated by `pgvisor setup`\n");
        out.push_str("volumes:\n");
        if bundled {
            out.push_str("  rustfs_data:\n");
        }
        out.push_str("  node1_data:\n");
        out.push_str("  node2_data:\n");
        out.push_str("  node3_data:\n");
        out.push_str("  proxy_tls_data:\n\n");
        out.push_str("services:\n");

        if bundled {
            out.push_str(&Self::render_rustfs());
        }

        out.push_str(&Self::render_node(1, "leader", bundled));
        out.push_str(&Self::render_node(2, "standby", bundled));
        out.push_str(&Self::render_node(3, "standby", bundled));
        out.push_str(&Self::render_proxy());
        out.push_str(&Self::render_dashboard());

        out
    }

    fn render_rustfs() -> String {
        r#"  rustfs:
    image: rustfs/rustfs:latest
    restart: unless-stopped
    ports:
      - "127.0.0.1:${S3_API_PORT:-9000}:9000"
      - "127.0.0.1:${S3_CONSOLE_PORT:-9001}:9001"
    environment:
      RUSTFS_ACCESS_KEY: ${S3_ACCESS_KEY}
      RUSTFS_SECRET_KEY: ${S3_SECRET_KEY}
      MINIO_ROOT_USER: ${S3_ACCESS_KEY}
      MINIO_ROOT_PASSWORD: ${S3_SECRET_KEY}
      RUSTFS_CONSOLE_ENABLE: "true"
    volumes:
      - rustfs_data:/data
    networks:
      default:
        aliases:
          - minio
    healthcheck:
      test: ["CMD", "curl", "-f", "http://127.0.0.1:9000/health"]
      interval: 3s
      timeout: 3s
      retries: 10

  rustfs-init:
    image: rustfs/rustfs:latest
    depends_on:
      rustfs:
        condition: service_healthy
    volumes:
      - ./scripts:/scripts:ro
    environment:
      S3_ENDPOINT: ${S3_ENDPOINT:-http://rustfs:9000}
      S3_BUCKET: ${S3_BUCKET:-pgvisor-backups}
      S3_REGION: ${S3_REGION:-us-east-1}
      S3_ACCESS_KEY: ${S3_ACCESS_KEY}
      S3_SECRET_KEY: ${S3_SECRET_KEY}
    entrypoint: ["/scripts/init-s3-bucket.sh"]

"#
        .to_string()
    }

    fn render_node(node_id: u8, role: &str, bundled_s3: bool) -> String {
        let mut s = String::with_capacity(1024);
        let _ = writeln!(s, "  pgvisor-node{node_id}:");
        let _ = writeln!(s, "    image: ${{PGVISOR_IMAGE:-dreamoutbox/pgvisor:latest}}");
        let _ = writeln!(s, "    restart: unless-stopped");
        let _ = writeln!(s, "    environment:");
        let _ = writeln!(s, "      POSTGRES_USER: ${{POSTGRES_USER:-postgres}}");
        let _ = writeln!(s, "      POSTGRES_PASSWORD: ${{POSTGRES_PASSWORD}}");
        let _ = writeln!(s, "      PGVISOR_SUPERUSER: ${{PGVISOR_SUPERUSER:-postgres}}");
        let _ = writeln!(s, "      PGPORT: 5432");
        let _ = writeln!(s, "      PGDATA: /var/lib/postgresql/data/pgdata");
        if node_id > 1 {
            let _ = writeln!(
                s,
                "      PRIMARY_CONNINFO: host=pgvisor-node1 port=5432 user=${{POSTGRES_USER:-postgres}}"
            );
        }
        let _ = writeln!(s, "      PGVISOR_CLUSTER_ID: ${{PGVISOR_CLUSTER_ID:-pgvisor-cluster}}");
        let _ = writeln!(s, "      PGVISOR_NODE_ID: {node_id}");
        let _ = writeln!(s, "      PGVISOR_ROLE: {role}");
        let _ = writeln!(
            s,
            "      PGVISOR_PEERS: http://pgvisor-node1:8080,http://pgvisor-node2:8080,http://pgvisor-node3:8080"
        );
        let _ = writeln!(s, "      S3_ENDPOINT: ${{S3_ENDPOINT}}");
        let _ = writeln!(s, "      S3_BUCKET: ${{S3_BUCKET:-pgvisor-backups}}");
        let _ = writeln!(s, "      S3_REGION: ${{S3_REGION:-us-east-1}}");
        let _ = writeln!(s, "      S3_ACCESS_KEY: ${{S3_ACCESS_KEY}}");
        let _ = writeln!(s, "      S3_SECRET_KEY: ${{S3_SECRET_KEY}}");
        let _ = writeln!(s, "      PGVISOR_CLUSTER_SECRET: ${{PGVISOR_CLUSTER_SECRET}}");
        let _ = writeln!(s, "      PGVISOR_API_SESSION_SECRET: ${{PGVISOR_API_SESSION_SECRET}}");
        let _ = writeln!(s, "      PGVISOR_TLS_ENABLED: ${{PGVISOR_TLS_ENABLED:-false}}");
        let _ = writeln!(s, "      RUST_LOG: ${{RUST_LOG:-info}}");
        let _ = writeln!(s, "    volumes:");
        let _ = writeln!(s, "      - node{node_id}_data:/var/lib/postgresql/data");
        if node_id == 1 && bundled_s3 {
            let _ = writeln!(s, "    depends_on:");
            let _ = writeln!(s, "      rustfs-init:");
            let _ = writeln!(s, "        condition: service_completed_successfully");
        } else if node_id > 1 {
            let _ = writeln!(s, "    depends_on:");
            let _ = writeln!(s, "      pgvisor-node1:");
            let _ = writeln!(s, "        condition: service_healthy");
        }
        let _ = writeln!(s, "    healthcheck:");
        let _ = writeln!(
            s,
            "      test: [\"CMD\", \"pg_isready\", \"-U\", \"${{POSTGRES_USER:-postgres}}\", \"-h\", \"127.0.0.1\"]"
        );
        let _ = writeln!(s, "      interval: 3s");
        let _ = writeln!(s, "      timeout: 3s");
        let _ = writeln!(s, "      retries: 10");
        let _ = writeln!(s);
        s
    }

    fn render_proxy() -> String {
        r#"  pgvisor-proxy:
    image: ${PGVISOR_IMAGE:-dreamoutbox/pgvisor:latest}
    entrypoint: ["pgvisor-proxy"]
    restart: unless-stopped
    ports:
      - "${PGVISOR_PROXY_PORT:-5432}:5432"
    environment:
      PGVISOR_PROXY_LISTEN: 0.0.0.0:5432
      PGVISOR_LEADER_ADDR: pgvisor-node1:5432
      PGVISOR_STANDBY_ADDRS: pgvisor-node2:5432,pgvisor-node3:5432
      PGVISOR_CLUSTER_SECRET: ${PGVISOR_CLUSTER_SECRET}
      PGVISOR_TLS_ENABLED: ${PGVISOR_TLS_ENABLED:-false}
      PGVISOR_TLS_REQUIRED: ${PGVISOR_TLS_REQUIRED:-false}
      PGVISOR_TLS_CERT_DIR: /var/lib/postgresql/tls
      RUST_LOG: ${RUST_LOG:-info}
    volumes:
      - proxy_tls_data:/var/lib/postgresql/tls
    depends_on:
      pgvisor-node1:
        condition: service_healthy
      pgvisor-node2:
        condition: service_healthy
      pgvisor-node3:
        condition: service_healthy

"#
        .to_string()
    }

    fn render_dashboard() -> String {
        r#"  pgvisor-dashboard:
    image: ${PGVISOR_IMAGE:-dreamoutbox/pgvisor:latest}
    entrypoint: ["pgvisor-dashboard"]
    restart: unless-stopped
    ports:
      - "${PGVISOR_DASHBOARD_BIND:-127.0.0.1}:${PGVISOR_DASHBOARD_PORT:-8080}:8080"
    environment:
      PGVISOR_DASHBOARD_LISTEN: 0.0.0.0:8080
      PGVISOR_SIDECAR_URLS: http://pgvisor-node1:8081,http://pgvisor-node2:8081,http://pgvisor-node3:8081
      PGVISOR_CLUSTER_ID: ${PGVISOR_CLUSTER_ID:-pgvisor-cluster}
      RUST_LOG: ${RUST_LOG:-info}
    depends_on:
      pgvisor-node1:
        condition: service_healthy
      pgvisor-node2:
        condition: service_healthy
      pgvisor-node3:
        condition: service_healthy
"#
        .to_string()
    }
}
