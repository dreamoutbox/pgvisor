use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use crate::cli::S3Mode;
use crate::error::CliError;
use crate::setup::compose_template::ComposeTemplate;
use crate::setup::generated_secrets::GeneratedSecrets;
use crate::setup::setup_options::SetupOptions;

const INIT_S3_BUCKET_SH: &str = r#"#!/usr/bin/env sh
set -eu

ENDPOINT="${S3_ENDPOINT:-http://rustfs:9000}"
BUCKET="${S3_BUCKET:-pgvisor-backups}"
ACCESS_KEY="${S3_ACCESS_KEY:-${RUSTFS_ACCESS_KEY:-}}"
SECRET_KEY="${S3_SECRET_KEY:-${RUSTFS_SECRET_KEY:-}}"
REGION="${S3_REGION:-us-east-1}"
MAX_ATTEMPTS="${MAX_ATTEMPTS:-30}"

EMPTY_PAYLOAD_SHA256="e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
TARGET_URL="${ENDPOINT}/${BUCKET}"

echo "Waiting for S3 endpoint ${ENDPOINT} and ensuring bucket '${BUCKET}' exists..."

attempt=1
while [ "${attempt}" -le "${MAX_ATTEMPTS}" ]; do
    if curl -s -f -X PUT \
        --aws-sigv4 "aws:amz:${REGION}:s3" \
        --user "${ACCESS_KEY}:${SECRET_KEY}" \
        -H "x-amz-content-sha256: ${EMPTY_PAYLOAD_SHA256}" \
        "${TARGET_URL}" > /dev/null 2>&1; then
        echo "Successfully initialized S3 bucket '${BUCKET}' at ${ENDPOINT}"
        exit 0
    fi

    if curl -s -f -I \
        --aws-sigv4 "aws:amz:${REGION}:s3" \
        --user "${ACCESS_KEY}:${SECRET_KEY}" \
        -H "x-amz-content-sha256: ${EMPTY_PAYLOAD_SHA256}" \
        "${TARGET_URL}" > /dev/null 2>&1; then
        echo "S3 bucket '${BUCKET}' already exists at ${ENDPOINT}"
        exit 0
    fi

    echo "Attempt ${attempt}/${MAX_ATTEMPTS}: S3 bucket not ready yet, retrying in 1s..."
    attempt=$((attempt + 1))
    sleep 1
done

echo "ERROR: Timed out waiting for S3 bucket '${BUCKET}' after ${MAX_ATTEMPTS} attempts." >&2
exit 1
"#;

/// Renders `.env` and writes cluster configuration artifacts with restrictive permissions.
pub struct EnvTemplate;

impl EnvTemplate {
    /// Renders `.env` contents from `SetupOptions` and `GeneratedSecrets`.
    pub fn render_env(options: &SetupOptions, secrets: &GeneratedSecrets) -> String {
        let mut out = String::with_capacity(1024);
        let s3_access = options
            .s3_access_key
            .as_deref()
            .unwrap_or(&secrets.s3_access_key);
        let s3_secret = options
            .s3_secret_key
            .as_deref()
            .unwrap_or(&secrets.s3_secret_key);
        let tls_flag = if options.tls { "true" } else { "false" };

        let _ = writeln!(out, "# Generated by `pgvisor setup`");
        let _ = writeln!(out, "PGVISOR_CLUSTER_ID={}", options.cluster_id);
        let _ = writeln!(out, "PGVISOR_IMAGE={}", options.image);
        let _ = writeln!(out, "PGVISOR_PROXY_PORT={}", options.proxy_port);
        let _ = writeln!(out, "PGVISOR_DASHBOARD_BIND={}", options.dashboard_bind);
        let _ = writeln!(out, "PGVISOR_DASHBOARD_PORT={}", options.dashboard_port);
        let _ = writeln!(out, "POSTGRES_USER=postgres");
        let _ = writeln!(out, "POSTGRES_PASSWORD={}", secrets.postgres_password);
        let _ = writeln!(out, "PGVISOR_SUPERUSER={}", options.superuser);
        let _ = writeln!(out, "PGVISOR_CLUSTER_SECRET={}", secrets.cluster_secret);
        let _ = writeln!(out, "PGVISOR_API_SESSION_SECRET={}", secrets.api_session_secret);
        let _ = writeln!(out, "PGVISOR_TLS_ENABLED={tls_flag}");
        let _ = writeln!(out, "PGVISOR_TLS_REQUIRED={tls_flag}");
        let _ = writeln!(out, "S3_ENDPOINT={}", options.s3_endpoint);
        let _ = writeln!(out, "S3_BUCKET={}", options.s3_bucket);
        let _ = writeln!(out, "S3_REGION={}", options.s3_region);
        let _ = writeln!(out, "S3_ACCESS_KEY={s3_access}");
        let _ = writeln!(out, "S3_SECRET_KEY={s3_secret}");
        if options.s3_mode == S3Mode::Bundled {
            let _ = writeln!(out, "S3_API_PORT={}", options.s3_api_port);
            let _ = writeln!(out, "S3_CONSOLE_PORT={}", options.s3_console_port);
        }
        out
    }

    /// Writes `docker-compose.yml`, `.env` (`0600`), and `scripts/init-s3-bucket.sh` (`0755` if bundled).
    pub fn write_cluster_files(
        dir: &Path,
        options: &SetupOptions,
        secrets: &GeneratedSecrets,
    ) -> Result<(), CliError> {
        fs::create_dir_all(dir).map_err(|source| CliError::Io {
            path: dir.to_path_buf(),
            source,
        })?;

        let compose_path = dir.join("docker-compose.yml");
        let env_path = dir.join(".env");

        if !options.force {
            if compose_path.exists() {
                return Err(CliError::FileAlreadyExists(compose_path));
            }
            if env_path.exists() {
                return Err(CliError::FileAlreadyExists(env_path));
            }
        }

        let compose_body = ComposeTemplate::render(options);
        fs::write(&compose_path, compose_body).map_err(|source| CliError::Io {
            path: compose_path,
            source,
        })?;

        let env_body = Self::render_env(options, secrets);
        fs::write(&env_path, env_body).map_err(|source| CliError::Io {
            path: env_path.clone(),
            source,
        })?;
        Self::set_permissions(&env_path, 0o600)?;

        if options.s3_mode == S3Mode::Bundled {
            let scripts_dir = dir.join("scripts");
            fs::create_dir_all(&scripts_dir).map_err(|source| CliError::Io {
                path: scripts_dir.clone(),
                source,
            })?;
            let init_script_path = scripts_dir.join("init-s3-bucket.sh");
            fs::write(&init_script_path, INIT_S3_BUCKET_SH).map_err(|source| CliError::Io {
                path: init_script_path.clone(),
                source,
            })?;
            Self::set_permissions(&init_script_path, 0o755)?;
        }

        Ok(())
    }

    #[cfg(unix)]
    fn set_permissions(path: &Path, mode: u32) -> Result<(), CliError> {
        use std::os::unix::fs::PermissionsExt;
        let perms = fs::Permissions::from_mode(mode);
        fs::set_permissions(path, perms).map_err(|source| CliError::Io {
            path: path.to_path_buf(),
            source,
        })
    }

    #[cfg(not(unix))]
    fn set_permissions(_path: &Path, _mode: u32) -> Result<(), CliError> {
        Ok(())
    }
}
